// One-time build tool: converts scripts/kenya_adm1.geojson (geoBoundaries, public domain)
// into a compact SVG path module for the homepage county choropleth.
// Run: node scripts/generate-kenya-shapes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const geo = JSON.parse(readFileSync(join(root, 'scripts', 'kenya_adm1.geojson'), 'utf8'));

const W = 360;
const H = 436;
const MIN_DIST = 1.1; // px — drop points closer than this to shrink path data

// Global bbox
let minLng = Infinity, maxLng = -Infinity, minLat = Infinity, maxLat = -Infinity;
const walk = (coords, cb) => {
  if (typeof coords[0] === 'number') return cb(coords);
  coords.forEach((c) => walk(c, cb));
};
for (const f of geo.features) {
  walk(f.geometry.coordinates, ([lng, lat]) => {
    if (lng < minLng) minLng = lng;
    if (lng > maxLng) maxLng = lng;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  });
}

const project = ([lng, lat]) => [
  ((lng - minLng) / (maxLng - minLng)) * W,
  ((maxLat - lat) / (maxLat - minLat)) * H,
];

const thinRing = (ring) => {
  const pts = ring.map(project);
  const out = [pts[0]];
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const [lx, ly] = out[out.length - 1];
    if (Math.hypot(x - lx, y - ly) >= MIN_DIST) out.push([x, y]);
  }
  out.push(pts[pts.length - 1]);
  return out;
};

const ringToPath = (ring) => {
  const pts = thinRing(ring);
  if (pts.length < 4) return '';
  const rounded = pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`);
  return `M${rounded.join('L')}Z`;
};

const counties = geo.features.map((f) => {
  const geom = f.geometry;
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  let d = '';
  for (const poly of polys) {
    for (const ring of poly) {
      d += ringToPath(ring);
    }
  }
  return { name: f.properties.shapeName, d };
});

const ts =
  '// Generated by scripts/generate-kenya-shapes.mjs from geoBoundaries KEN ADM1 (public domain).\n' +
  `export const KENYA_VIEWBOX = '0 0 ${W} ${H}';\n\n` +
  'export interface KenyaCountyShape {\n  name: string;\n  d: string;\n}\n\n' +
  `export const KENYA_COUNTIES: KenyaCountyShape[] = ${JSON.stringify(counties)};\n`;

writeFileSync(join(root, 'src', 'components', 'home', 'kenyaCountyShapes.ts'), ts);
console.log('counties:', counties.length, 'bytes:', ts.length);
