// Generates src/lib/countyCentroids.ts from Kenya ADM1 boundaries
// (geoBoundaries open data, same file previously vendored as scripts/kenya_adm1.geojson).
// Usage: node scripts/generate-county-centroids.mjs

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const geojsonPath = path.join(root, 'scripts', 'kenya_adm1.geojson');

let raw;
if (fs.existsSync(geojsonPath)) {
  raw = fs.readFileSync(geojsonPath, 'utf8');
} else {
  // File was removed from the worktree; recover it from git history.
  raw = execSync('git show HEAD:scripts/kenya_adm1.geojson', { cwd: root, maxBuffer: 64 * 1024 * 1024 }).toString('utf8');
}

const geojson = JSON.parse(raw);

// Area-weighted centroid of (Multi)Polygon geometries using the shoelace formula.
function ringCentroid(ring) {
  let area = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0, n = ring.length - 1; i < n; i++) {
    const [x0, y0] = ring[i];
    const [x1, y1] = ring[i + 1];
    const cross = x0 * y1 - x1 * y0;
    area += cross;
    cx += (x0 + x1) * cross;
    cy += (y0 + y1) * cross;
  }
  area /= 2;
  if (Math.abs(area) < 1e-12) {
    const [sx, sy] = ring.reduce((acc, [x, y]) => [acc[0] + x, acc[1] + y], [0, 0]);
    return { lng: sx / ring.length, lat: sy / ring.length, area: 0 };
  }
  return { lng: cx / (6 * area), lat: cy / (6 * area), area: Math.abs(area) };
}

function geometryCentroid(geometry) {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  let totalArea = 0;
  let lng = 0;
  let lat = 0;
  for (const polygon of polygons) {
    const c = ringCentroid(polygon[0]); // outer ring only
    totalArea += c.area;
    lng += c.lng * c.area;
    lat += c.lat * c.area;
  }
  if (totalArea === 0) return null;
  return { lat: lat / totalArea, lng: lng / totalArea };
}

const normalize = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '');

// Common alternate spellings mapped onto a geoBoundaries shapeName key.
const ALIASES = {
  tharakanithi: 'tharaka',
};

const entries = [];
for (const feature of geojson.features) {
  const name = feature.properties.shapeName;
  const centroid = geometryCentroid(feature.geometry);
  if (!centroid) {
    console.error(`Skipped ${name}: could not compute centroid`);
    continue;
  }
  entries.push({
    key: normalize(name),
    name,
    lat: Number(centroid.lat.toFixed(4)),
    lng: Number(centroid.lng.toFixed(4)),
  });
}

entries.sort((a, b) => a.name.localeCompare(b.name));

const lines = entries.map(
  (e) => `  ${JSON.stringify(e.key)}: { name: ${JSON.stringify(e.name)}, lat: ${e.lat}, lng: ${e.lng} },`
);

const out = `// Generated by scripts/generate-county-centroids.mjs — do not edit by hand.
// Centroids computed from Kenya ADM1 boundaries (geoBoundaries open data).
// Keys are normalized county names (lowercase, alphanumeric only).

export interface CountyCentroid {
  name: string;
  lat: number;
  lng: number;
}

export const COUNTY_CENTROIDS: Record<string, CountyCentroid> = {
${lines.join('\n')}
};

const ALIASES: Record<string, string> = ${JSON.stringify(ALIASES, null, 2)};

export function normalizeCountyName(name?: string | null): string {
  return (name || '').toLowerCase().replace(/[^a-z0-9]+/g, '');
}

export function getCountyCentroid(name?: string | null): CountyCentroid | null {
  const key = normalizeCountyName(name);
  return COUNTY_CENTROIDS[key] || COUNTY_CENTROIDS[ALIASES[key]] || null;
}
`;

fs.writeFileSync(path.join(root, 'src', 'lib', 'countyCentroids.ts'), out);
console.log(`Wrote ${entries.length} county centroids to src/lib/countyCentroids.ts\n`);
for (const e of entries) console.log(`${e.name.padEnd(22)} ${e.lat.toFixed(4)}, ${e.lng.toFixed(4)}`);
